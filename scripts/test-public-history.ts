// Checks the full-history rewrite (scripts/public-history.ts) on a small fixture repository. No network, no gh, no gitleaks needed.
//   node scripts/test-public-history.ts
// Exits 1, one FAIL line per problem.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { PRODUCT_NAME } from "../packages/gantt/src/product.ts";
import { cleanMessage, count, gitleaks, pruneAllowlist, rewrite } from "./public-history.ts";

let failed = false;
const check = (name: string, got: unknown, want: unknown): void => {
  if (JSON.stringify(got) === JSON.stringify(want)) return;
  failed = true;
  console.error(`test-public-history: FAIL ${name}: got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`);
};

process.env.PUBLIC_RELEASE_NAMES = "Acme Corp";
const domain = `${PRODUCT_NAME.toLowerCase()}.com`;
const generated = "🤖 Generated with [Claude Code](https://claude.com/claude-code)";
const trailer = "Co-authored-by: Claude <noreply@anthropic.com>";
check("the trailer, the address and the name go; a noreply address and the product domain stay", cleanMessage(`one\n\nWrote it for Acme Corp, mail dev@example.org or hello@${domain} or noreply@github.com.\n\n${trailer}\n`, /acme corp/gi),
  `one\n\nWrote it for the partner, mail [address removed] or hello@${domain} or noreply@github.com.\n`);
check("the generated line goes, a sentence that mentions it stays", cleanMessage(`x\n\nWe drop the Generated with Claude Code line.\n\n${generated}\n`, null), "x\n\nWe drop the Generated with Claude Code line.\n");
check("the wrapped, underscored form goes too", cleanMessage("x\n\n_Generated by [Claude\nCode](https://claude.ai/code/session_1)_\n", null), "x\n");
const self = "crates/app/tests/architecture/name/allowlist.txt", retired = ["gantt", "spike"].join("-");
check("the allowlist keeps its own line while a kept line names a retired name", pruneAllowlist(`# c\n${self}\na.ts | ${retired}\nb.ts\n`, new Set(["a.ts", self]), self), `# c\n${self}\na.ts | ${retired}\n`);
check("the allowlist drops its own line when none does", pruneAllowlist(`# c\n${self}\na.ts | x\nb.ts\n`, new Set(["a.ts", self]), self), `# c\na.ts | x\n`);
check("another person's trailer stays", cleanMessage("x\n\nCo-authored-by: Pat <pat@users.noreply.github.com>\n", null), "x\n\nCo-authored-by: Pat <pat@users.noreply.github.com>\n");

const root = mkdtempSync(join(tmpdir(), "public-history-test-"));
const [src, dest, again] = ["src", "dest", "again"].map((d) => join(root, d));
const run = (cwd: string, ...args: string[]) => execFileSync("git", ["-C", cwd, "-c", "user.name=Dev", "-c", "user.email=dev@example.org", ...args], { encoding: "utf8" });
const noreply = "7+dev@users.noreply.github.com";
try {
  mkdirSync(src);
  run(src, "init", "-q", "-b", "main");
  mkdirSync(join(src, "docs"));
  writeFileSync(join(src, "README.md"), "hello\n");
  writeFileSync(join(src, "NOTES.md"), "private\n");
  const list = "crates/app/tests/architecture/name/allowlist.txt";
  mkdirSync(join(src, "crates/app/tests/architecture/name"), { recursive: true });
  writeFileSync(join(src, list), `# note\nREADME.md | x # why\nNOTES.md | y\n${list}\ngone.ts\n`);
  run(src, "add", "-A"); run(src, "commit", "-q", "-m", `first\n\n${trailer}`);
  writeFileSync(join(src, "NOTES.md"), "private two\n");
  run(src, "commit", "-q", "-am", "reply to dev@example.org about Acme Corp");
  writeFileSync(join(src, "docs/ARCHITECTURE.md"), "design\n");
  run(src, "add", "-A"); run(src, "commit", "-q", "-m", `third\n\n${generated}`);

  const { before, after } = rewrite(src, dest, { email: noreply, name: "Dave Remy" });
  check("commits before", before.commits, 3);
  check("the commit that touched only dropped files is gone", after.commits, 2);
  check("one address on every commit, author and committer", [after["author emails"], after["committer emails"]], [1, 1]);
  check("the address is the one given", run(dest, "log", "--format=%an <%ae> %cn <%ce>").trim().split("\n"), Array(2).fill(`Dave Remy <${noreply}> Dave Remy <${noreply}>`));
  check("no assistant trailer left", [before["assistant trailers"], after["assistant trailers"]], [2, 0]);
  check("no personal address, no name, nothing outside the set", [after["personal address in a message or header"], after["personal address in a diff"], after["name in a message"], after["name in a diff"], after["paths outside the public set"]], [0, 0, 0, 0, 0]);
  check("the personal address and the name were there before", [before["personal address in a message or header"], before["name in a message"]], [3, 1]);
  check("only the public paths remain", run(dest, "ls-tree", "-r", "--name-only", "HEAD").trim().split("\n"), ["README.md", list, "docs/ARCHITECTURE.md"]);
  check("the allowlist keeps only lines for paths the commit holds, and not its own line when no kept line names a retired name, in every commit", ["HEAD", "HEAD~1"].map((c) => run(dest, "show", `${c}:${list}`)), Array(2).fill("# note\nREADME.md | x # why\n"));
  check("the clone has no remote and no old refs", [run(dest, "remote"), run(dest, "for-each-ref", "refs/original")], ["", ""]);
  check("the source is untouched", count(src, ["dev@example.org"], null).commits, 3);
  check("a second run into that directory is refused", (() => { try { rewrite(src, dest, { email: noreply, name: "x" }); return "ran"; } catch { return "refused"; } })(), "refused");
  check("a missing scanner is null, never a pass", gitleaks(dest, join(root, "no-such-gitleaks")), null);
  check("a fresh scratch directory works again", rewrite(src, again, { email: noreply, name: "Dave Remy" }).after.commits, 2);
} finally {
  rmSync(root, { recursive: true, force: true });
}

process.exit(failed ? 1 : 0);
